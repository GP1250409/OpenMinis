#!/usr/bin/env python3
"""Reproduce the offline US geometry (Python stdlib only; run on RN).
Natural Earth 1:50m admin-1, public domain. No client networking.
Spherical Albers equal-area; simplify in projected space, preserve ring holes.
Usage: python3 scripts/generate_map_data.py [--input states.geojson]
"""
import argparse, hashlib, json, math, pathlib, urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]
URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/ca96624a56bd078437bca8184e78163e5039ad19/geojson/ne_50m_admin_1_states_provinces.geojson'
SPECS = {'main': (29.5,45.5,-96,23), 'AK': (55,65,-154,50), 'HI': (8,18,-157,13)}
FRAMES = {'main': (20,0,960,520), 'AK': (30,445,240,175), 'HI': (300,540,145,80)}
def project(lon,lat,spec):
    a,b,l0,p0 = [math.radians(x) for x in spec]
    if spec == SPECS['AK'] and lon > 0: lon -= 360
    l,p = math.radians(lon),math.radians(lat)
    n = (math.sin(a)+math.sin(b))/2
    c = math.cos(a)**2+2*n*math.sin(a)
    rho = math.sqrt(c-2*n*math.sin(p))/n
    r0 = math.sqrt(c-2*n*math.sin(p0))/n
    t = n*(l-l0)
    return rho*math.sin(t), r0-rho*math.cos(t)
def simplify(points,tolerance):
    # Iterative RDP avoids recursion limits for long coastline rings.
    if len(points)<4: return points
    keep = {0,len(points)-1}; stack = [(0,len(points)-1)]
    while stack:
        first,last = stack.pop(); ax,ay = points[first]; bx,by = points[last]
        dx,dy=bx-ax,by-ay; d2=dx*dx+dy*dy; best,index=0,None
        for i in range(first+1,last):
            x,y=points[i]; t=max(0,min(1,((x-ax)*dx+(y-ay)*dy)/d2)) if d2 else 0
            d=(x-ax-t*dx)**2+(y-ay-t*dy)**2
            if d>best: best,index=d,i
        if index is not None and best>tolerance*tolerance:
            keep.add(index); stack.extend([(first,index),(index,last)])
    result=[points[i] for i in sorted(keep)]
    return result if len(result)>=4 else points[:3]+[points[0]]
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--input',type=pathlib.Path); args=ap.parse_args()
    raw=args.input.read_bytes() if args.input else urllib.request.urlopen(URL,timeout=90).read()
    features=[f for f in json.loads(raw)['features'] if f['properties'].get('admin')=='United States of America']
    assert len(features)==51
    regions={}; groups={k:[] for k in SPECS}
    for f in features:
        code=f['properties']['postal']; key=code if code in ('AK','HI') else 'main'
        geom=f['geometry']; polys=geom['coordinates'] if geom['type']=='MultiPolygon' else [geom['coordinates']]
        rings=[[project(lon,lat,SPECS[key]) for lon,lat,*_ in ring] for poly in polys for ring in poly]
        regions[code]=(key,rings); groups[key].extend(p for r in rings for p in r)
    bounds={k:(min(x for x,y in v),min(y for x,y in v),max(x for x,y in v),max(y for x,y in v)) for k,v in groups.items()}
    def normalized(x,y,key):
        x0,y0,x1,y1=bounds[key]; fx,fy,fw,fh=FRAMES[key]
        scale=min(fw/(x1-x0),fh/(y1-y0))
        return fx+(fw-(x1-x0)*scale)/2+(x-x0)*scale,fy+(fh-(y1-y0)*scale)/2+(y1-y)*scale
    rows=[]; vertices=0
    for code,(key,rings) in sorted(regions.items()):
        encoded=[]
        for r in rings:
            norm=[normalized(x,y,key) for x,y in simplify(r,0.00045)]
            # Skip subpixel offshore specks, never the largest/main ring (DC retained).
            if max(x for x,y in norm)-min(x for x,y in norm)<0.25 and code!='DC': continue
            encoded.append(';'.join(f'{x:.1f},{y:.1f}' for x,y in norm)); vertices+=len(norm)
        rows.append(code+'|'+'/'.join(encoded))
    transforms=[]
    for key in SPECS:
        spec=', '.join(str(x) for x in SPECS[key]); b=', '.join(repr(x) for x in bounds[key]); frame=', '.join(str(x) for x in FRAMES[key])
        transforms.append(f'        "{key}": MUMapProjectionSpec(parallels: [{spec}], bounds: [{b}], frame: [{frame}]),')
    header='// Generated by scripts/generate_map_data.py. Natural Earth public domain.\n// Input SHA256: '+hashlib.sha256(raw).hexdigest()+'\nimport Foundation\n#if canImport(CoreGraphics)\nimport CoreGraphics\n#endif\n\nenum MUMapGeometry {\n    static let specs: [String:MUMapProjectionSpec] = [\n'+'\n'.join(transforms)+'\n    ]\n'
    decoder='''    static let us: [(code:String, rings:[[CGPoint]])] = encoded.split(separator: "\\n").compactMap { line in
        let pair = line.split(separator: "|", maxSplits:1)
        guard pair.count == 2 else { return nil }
        let rings: [[CGPoint]] = pair[1].split(separator: "/").map { ring in
            ring.split(separator: ";").compactMap { token in
                let xy = token.split(separator: ",").compactMap { Double($0) }
                return xy.count == 2 ? CGPoint(x:xy[0],y:xy[1]) : nil
            }
        }
        return (String(pair[0]),rings)
    }
    private static let encoded = """
'''
    out=ROOT/'src/ios/Views/Chat/AIChatView/MinisUI/MinisUIMapData.swift'
    out.write_text(header+decoder+'\n'.join(rows)+'\n"""\n}\n')
    print(f'MAP_DATA_GENERATED states={len(rows)} vertices={vertices} bytes={out.stat().st_size} input_sha256={hashlib.sha256(raw).hexdigest()}')
if __name__=='__main__': main()
